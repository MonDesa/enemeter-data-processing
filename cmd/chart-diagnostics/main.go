package main

import (
	"enemeter-data-processing/internal/parser"
	"enemeter-data-processing/internal/viz"
	"flag"
	"fmt"
	"os"
	"time"
)

func main() {
	inputFile := flag.String("input", "", "Input CSV file to analyze")
	startTime := flag.String("start", "", "Start time for measurements (format: YYYY-MM-DD HH:MM:SS)")
	chartType := flag.String("type", "power", "Type of chart to diagnose (power, energy, voltage, current, temperature)")
	timeScale := flag.String("time-scale", "hours", "Time scale (milliseconds, seconds, minutes, hours, days)")
	maxPoints := flag.Int("max-points", 2000, "Maximum number of points to generate")
	samplingMode := flag.String("sampling", "adaptive", "Sampling mode (even, adaptive, lttb)")
	flag.Parse()

	if *inputFile == "" || *startTime == "" {
		fmt.Println("Usage: chart-diagnostics --input=data.csv --start=\"2023-04-01 08:00:00\"")
		os.Exit(1)
	}

	fmt.Printf("Chart Diagnostics for file: %s\n\n", *inputFile)

	// Parse the file
	startTimeObj, err := time.Parse("2006-01-02 15:04:05", *startTime)
	if err != nil {
		fmt.Printf("Error parsing start time: %v\n", err)
		os.Exit(1)
	}

	// Create parser
	csvParser := parser.NewCSVParser(*inputFile)
	csvParser.WithFilterOptions(parser.FilterOptions{
		StartTime: &startTimeObj,
	})

	// Parse records
	records, err := csvParser.Parse()
	if err != nil {
		fmt.Printf("Error parsing file: %v\n", err)
		os.Exit(1)
	}

	// Basic dataset analysis
	fmt.Printf("Dataset information:\n")
	fmt.Printf("- Total records: %d\n", len(records))
	if len(records) > 0 {
		fmt.Printf("- Time range: %s to %s\n",
			records[0].Timestamp.Format("2006-01-02 15:04:05"),
			records[len(records)-1].Timestamp.Format("2006-01-02 15:04:05"))

		duration := records[len(records)-1].Timestamp.Sub(records[0].Timestamp)
		fmt.Printf("- Duration: %s (%.2f hours)\n", duration.Round(time.Second), duration.Hours())
	}

	// Create graphics generator for testing
	generator := viz.NewGraphicsGenerator(records, "diagnose")
	generator.WithMaxDataPoints(*maxPoints)
	generator.WithSamplingMode(*samplingMode)
	generator.WithScaleOptions(viz.ScaleOptions{
		TimeScale: *timeScale,
	})

	// For energy chart, calculate and diagnose energy data specifically
	if *chartType == "energy" {
		fmt.Printf("\nAnalyzing energy chart data generation:\n")
		energyCalc := viz.NewEnergyCalculation(records)
		timestamps, energyValues := energyCalc.CalculateCumulativeEnergy()
		fmt.Printf("Generated %d timestamps and %d energy values\n", len(timestamps), len(energyValues))

		// Analyze timestamps distribution
		fmt.Printf("\nTimestamp Distribution Analysis:\n")
		if len(timestamps) > 0 {
			fmt.Printf("- First energy timestamp: %s\n", timestamps[0].Format("2006-01-02 15:04:05"))
			fmt.Printf("- Last energy timestamp: %s\n", timestamps[len(timestamps)-1].Format("2006-01-02 15:04:05"))
			fmt.Printf("- Energy time range: %.2f hours\n",
				timestamps[len(timestamps)-1].Sub(timestamps[0]).Hours())

			// Check for large gaps in timestamps
			fmt.Printf("\nChecking for large gaps in energy timestamps...\n")
			maxGap := time.Duration(0)
			maxGapStart := time.Time{}
			gapsOver1Min := 0
			gapsOver10Min := 0

			for i := 1; i < len(timestamps); i++ {
				gap := timestamps[i].Sub(timestamps[i-1])
				if gap > maxGap {
					maxGap = gap
					maxGapStart = timestamps[i-1]
				}

				if gap > time.Minute {
					gapsOver1Min++
				}

				if gap > 10*time.Minute {
					gapsOver10Min++
					fmt.Printf("  Large gap (%.1f minutes) at %s\n",
						gap.Minutes(), timestamps[i-1].Format("2006-01-02 15:04:05"))
				}
			}

			fmt.Printf("- Largest gap in energy data: %.1f minutes at %s\n",
				maxGap.Minutes(), maxGapStart.Format("2006-01-02 15:04:05"))
			fmt.Printf("- Gaps > 1 minute: %d\n", gapsOver1Min)
			fmt.Printf("- Gaps > 10 minutes: %d\n", gapsOver10Min)
		} else {
			fmt.Printf("No energy data points were generated!\n")
		}
	}

	// Simulate chart rendering process for the specified type
	fmt.Printf("\nSimulating chart data generation for %s chart with %s time scale:\n", *chartType, *timeScale)

	// Track the resulting time range that would appear on the chart
	var chartStartTime, chartEndTime time.Time
	var chartPoints int

	switch viz.GraphType(*chartType) {
	case viz.GraphTypePower:
		fmt.Println("Analyzing power chart data points...")
		// This is a simplified simulation - in a real implementation we would analyze
		// the actual points generated by the chart function
		chartStartTime = records[0].Timestamp
		chartEndTime = records[len(records)-1].Timestamp
		chartPoints = *maxPoints

	case viz.GraphTypeEnergy:
		fmt.Println("Analyzing energy chart data points...")
		// For energy charts, we can use the actual calculation
		energyCalc := viz.NewEnergyCalculation(records)
		timestamps, _ := energyCalc.CalculateCumulativeEnergy()
		if len(timestamps) > 0 {
			chartStartTime = timestamps[0]
			chartEndTime = timestamps[len(timestamps)-1]
			chartPoints = len(timestamps)
			if *maxPoints > 0 && chartPoints > *maxPoints {
				chartPoints = *maxPoints
			}
		}

	default:
		// For other chart types, estimate based on records
		chartStartTime = records[0].Timestamp
		chartEndTime = records[len(records)-1].Timestamp
		chartPoints = *maxPoints
	}

	fmt.Printf("\nExpected chart visualization:\n")
	fmt.Printf("- Chart will show from %s to %s\n",
		chartStartTime.Format("2006-01-02 15:04:05"),
		chartEndTime.Format("2006-01-02 15:04:05"))
	fmt.Printf("- Chart time range: %.2f hours\n", chartEndTime.Sub(chartStartTime).Hours())
	fmt.Printf("- Approx. chart points: %d\n", chartPoints)

	// Verify vs. actual dataset
	if len(records) > 0 {
		dataStart := records[0].Timestamp
		dataEnd := records[len(records)-1].Timestamp
		chartStartDiff := chartStartTime.Sub(dataStart).Minutes()
		chartEndDiff := dataEnd.Sub(chartEndTime).Minutes()

		if chartStartDiff > 5 || chartEndDiff > 5 {
			fmt.Printf("\nWARNING: Chart time range differs from dataset time range!\n")
			fmt.Printf("- Dataset: %s to %s (%.2f hours)\n",
				dataStart.Format("2006-01-02 15:04:05"),
				dataEnd.Format("2006-01-02 15:04:05"),
				dataEnd.Sub(dataStart).Hours())
			fmt.Printf("- Chart:   %s to %s (%.2f hours)\n",
				chartStartTime.Format("2006-01-02 15:04:05"),
				chartEndTime.Format("2006-01-02 15:04:05"),
				chartEndTime.Sub(chartStartTime).Hours())
			fmt.Printf("- Start difference: %.1f minutes\n", chartStartDiff)
			fmt.Printf("- End difference: %.1f minutes\n", chartEndDiff)
		} else {
			fmt.Printf("\nChart time range matches dataset time range ✓\n")
		}
	}

	// Recommendations
	fmt.Printf("\nRecommendations:\n")
	if len(records) > 500000 {
		fmt.Printf("- Dataset is very large (%d records). Consider using --sample=5 or higher\n", len(records))
	}

	if chartEndTime.Sub(chartStartTime).Hours() > 12 {
		fmt.Printf("- Time range is large (%.1f hours). Consider using --time-scale=hours\n",
			chartEndTime.Sub(chartStartTime).Hours())
	}

	if *maxPoints < 1000 && len(records) > 100000 {
		fmt.Printf("- Current max-points (%d) may be too low for your data. Consider 1000-2000\n", *maxPoints)
	}

	fmt.Printf("\nTo fix time range issues, try:\n")
	fmt.Printf("1. Use --time-scale=hours to properly display multi-hour timeframes\n")
	fmt.Printf("2. Use --sampling=lttb which preserves overall data shape well\n")
	fmt.Printf("3. Use --max-points=2000 for better resolution\n")
}
